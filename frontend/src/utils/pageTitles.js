/** "Lesson · Systematic Theology I · Seminary" for a route. */
export function pageTitle(route, school = '') {
	const title = TITLES[route.name]
	const parts = [title ? title() : __('Seminary')]
	const course = route.params?.courseName
	if (course) parts.push(decodeURIComponent(String(course)))
	if (school) parts.push(school)
	return parts.join(' · ')
}

export function hasTitle(name) {
	return Object.prototype.hasOwnProperty.call(TITLES, name)
}
